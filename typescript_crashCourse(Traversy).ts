// testing number data types
let myNum : number;

// negative integer
myNum = -22;
console.log(myNum);     // prints -22

// expression
myNum = 5 /10;
console.log(myNum);     // prints 0.5

// decimal
myNum = 7.8643;
console.log(myNum);         // prints 7.8643

// hexadecimal
myNum = 0xf00d;
console.log(myNum);     // prints 61453
























































































